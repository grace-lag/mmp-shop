type Props = { onPick: (emoji: string) => void; onClose?: () => void };

export function EmojiPicker({ onPick, onClose }: Props) {
  const [active, setActive] = useState(0);
  const cat = CATEGORIES[active];
  return (
    <div
      style={{
        background: "#fff", border: "1px solid #e2e8f0", borderRadius: 12,
        boxShadow: "0 8px 24px rgba(0,0,0,0.08)", width: "min(360px, 95vw)",
        maxHeight: 360, display: "flex", flexDirection: "column",
      }}
    >
      <div style={{ display: "flex", gap: 4, padding: 6, borderBottom: "1px solid #f1f5f9", overflowX: "auto" }}>
        {CATEGORIES.map((c, i) => (
          <button
            key={c.name}
            type="button"
            onClick={() => setActive(i)}
            title={c.name}
            style={{
              background: i === active ? "#f1f5f9" : "transparent",
              border: 0, borderRadius: 8, padding: "6px 8px", cursor: "pointer", fontSize: 18,
            }}
          >
            {c.icon}
          </button>
        ))}
        {onClose && (
          <button type="button" onClick={onClose} style={{ marginLeft: "auto", background: "transparent", border: 0, cursor: "pointer", color: "#94a3b8", fontSize: 18 }}>×</button>
        )}
      </div>
      <div style={{ padding: 8, overflowY: "auto", display: "grid", gridTemplateColumns: "repeat(8, 1fr)", gap: 2 }}>
        {cat.emojis.map((e, i) => (
          <button
            key={`${e}-${i}`}
            type="button"
            onClick={() => onPick(e)}
            style={{ background: "none", border: 0, cursor: "pointer", fontSize: 22, padding: 4, borderRadius: 6 }}
            onMouseEnter={(ev) => (ev.currentTarget.style.background = "#f1f5f9")}
            onMouseLeave={(ev) => (ev.currentTarget.style.background = "transparent")}
          >
            {e}
          </button>
        ))}
      </div>
    </div>
  );
}
